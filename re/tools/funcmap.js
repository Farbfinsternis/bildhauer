// Builds a function map from the annotated listing: for every function, the
// string literals it references. Debug strings in Sculptris often name the
// function ("AddTriangle()", "CollapseEdge"), which makes this a quick index.
// Usage: node funcmap.js <annotated.asm> > function-map.md
const fs = require('fs');
const lines = fs.readFileSync(process.argv[2], 'latin1').split('\n');
const funcs = [];
let cur = null;
for (const l of lines) {
  const f = /^sub_([0-9A-F]{8}):/.exec(l);
  if (f) { cur = { addr: f[1], strings: [], calls: 0, size: 0 }; funcs.push(cur); continue; }
  if (!cur) continue;
  if (/^\s+[0-9A-F]{8}:/.test(l)) cur.size++;
  if (/\bcall\b/.test(l)) cur.calls++;
  const s = /; (".*")$/.exec(l);
  if (s) { const v = JSON.parse(s[1]); if (!cur.strings.includes(v)) cur.strings.push(v); }
}
const named = funcs.filter(f => f.strings.length);
console.log('# Function map (functions with string references)\n');
console.log(`Generated by \`tools/funcmap.js\`. ${funcs.length} call targets, ${named.length} with strings.\n`);
console.log('| Address | Instr. | First strings |\n|---|---|---|');
for (const f of named) {
  const s = f.strings.slice(0, 4).map(x => '`' + x.replace(/\|/g, '\\|').replace(/`/g, "'").slice(0, 60) + '`').join(', ');
  console.log(`| 0x${f.addr} | ${f.size} | ${s}${f.strings.length > 4 ? ` (+${f.strings.length - 4})` : ''} |`);
}
